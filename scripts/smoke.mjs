async function assertTerminalGutter(page) {
  await page.waitForFunction(() => {
    const screen = document.querySelector('.terminal-mount .xterm-screen'), bar = document.querySelector('.terminal-mount .scrollbar.vertical'), mount = document.querySelector('.terminal-mount');
    if (!screen || !bar || !mount) return false;
    const s = screen.getBoundingClientRect(), b = bar.getBoundingClientRect(), m = mount.getBoundingClientRect();
    const rows = screen.querySelector('.xterm-rows')?.childElementCount ?? 0, rowHeight = rows ? s.height / rows : 0;
    return s.width > 0 && b.width >= 12 && s.right <= b.left + 1 && s.bottom <= m.bottom + 1 && b.right <= m.right + 1 && rowHeight > 0 && m.bottom - s.bottom < rowHeight + 1;
  });
}
async function eventually(check, description, timeout = 15000) {
  const deadline = Date.now() + timeout;
  while (!await check()) { assert.ok(Date.now() < deadline, description); await new Promise(resolve => setTimeout(resolve, 70)); }
}
async function fileExists(file) { try { await stat(file); return true; } catch (error) { if (error.code === 'ENOENT') return false; throw error; } }
function shellCommand(script) {
  return process.platform === 'win32' ? `"${process.execPath}" "${script}"` : `'${process.execPath.replaceAll("'", "'\\''")}' '${script.replaceAll("'", "'\\''")}'`;
}
async function closeApplication(app) {
  if (!app) return;
  const launcherProcess = app.process();
  // A detached daemon may retain inherited pipe handles. Node's child "close"
  // event can then arrive after "exit"; wait for the actual launcher exit.
  let onExit;
  const exited = launcherProcess.exitCode !== null || launcherProcess.signalCode !== null ? Promise.resolve() : new Promise(resolve => { onExit = resolve; launcherProcess.once('exit', onExit); });
  let timer;
  try {
    await Promise.race([exited, app.close(), new Promise((_, reject) => { timer = setTimeout(() => reject(new Error('Electron workbench did not exit within 20s')), 20000); })]);
  } finally { clearTimeout(timer); if (onExit) launcherProcess.removeListener('exit', onExit); }
}
async function forceCleanup(app) {
  if (!app) return;
  const pid = app.process().pid;
  try {
    if (process.platform === 'win32') await execute('taskkill.exe', ['/PID', String(pid), '/T', '/F'], { windowsHide: true, timeout: 5000 });
    else app.process().kill('SIGKILL');
  } catch {}
}

